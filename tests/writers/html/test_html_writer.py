"""HtmlWriter: the target that turns a device into an HTML register reference."""

import subprocess
import sys
from html.parser import HTMLParser

from regforge.writers import HtmlWriter, available_writers, get_writer, writer_for_path

_VOID = {"meta", "br", "link", "img", "hr", "input"}


class _Balance(HTMLParser):
    """Tracks open tags so a test can tell the page is well formed."""

    def __init__(self):
        super().__init__()
        self.stack: list[str] = []
        self.errors: list[str] = []

    def handle_starttag(self, tag, attrs):
        if tag not in _VOID:
            self.stack.append(tag)

    def handle_endtag(self, tag):
        if self.stack and self.stack[-1] == tag:
            self.stack.pop()
        else:
            self.errors.append(tag)


def test_html_is_a_registered_target_chosen_by_name_or_extension():
    assert "html" in available_writers()
    assert isinstance(get_writer("html"), HtmlWriter)
    assert isinstance(writer_for_path("docs/chip.html"), HtmlWriter)


def test_the_same_device_gives_the_same_bytes(demo_device):
    assert HtmlWriter().render(demo_device) == HtmlWriter().render(demo_device)


def test_the_page_is_well_formed(demo_device):
    parser = _Balance()
    parser.feed(HtmlWriter().render(demo_device))
    assert parser.errors == [] and parser.stack == []


def test_the_lint_fixture_page_is_well_formed_too(lint_demo_device):
    parser = _Balance()
    parser.feed(HtmlWriter().render(lint_demo_device))
    assert parser.errors == [] and parser.stack == []


def test_the_page_ends_with_a_newline(demo_device):
    assert HtmlWriter().render(demo_device).endswith("</html>\n")


def test_the_command_line_writes_an_html_file_from_an_svd(minimal_svd_path, tmp_path):
    out = tmp_path / "chip.html"
    subprocess.run(
        [sys.executable, "-m", "regforge", str(minimal_svd_path), "-o", str(out)],
        check=True,
        capture_output=True,
    )
    text = out.read_text(encoding="utf-8")
    assert text.startswith("<!DOCTYPE html>") and "GPIOA.MODER" in text
    assert "Generated by regforge" in text
